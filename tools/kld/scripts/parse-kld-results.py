#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any


PATTERNS = {
    "mean_ppl_q": re.compile(r"Mean PPL\(Q\)\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "mean_ppl_base": re.compile(r"Mean PPL\(base\)\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "mean_log_ppl_ratio": re.compile(r"Mean ln\(PPL\(Q\)/PPL\(base\)\)\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "mean_ppl_ratio": re.compile(r"Mean PPL\(Q\)/PPL\(base\)\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "mean_ppl_diff": re.compile(r"Mean PPL\(Q\)-PPL\(base\)\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "mean_kld": re.compile(r"Mean\s+KLD:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)"),
    "kld_p999": re.compile(r"99\.9%\s+KLD:\s*([0-9.eE+-]+)"),
    "rms_dp_percent": re.compile(r"RMS .*p\s*:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)\s*%"),
    "same_top_p_percent": re.compile(r"Same top p:\s*([0-9.eE+-]+)\s*(?:\+/-|±)\s*([0-9.eE+-]+)\s*%"),
}


def parse_ubatch(path: Path) -> int | None:
    match = re.search(r"ubatch[_-](\d+)", path.name)
    return int(match.group(1)) if match else None


def count_diagnostic_files(exp_dir: Path, case: str) -> dict[str, int]:
    diag_dir = exp_dir / "diagnostics" / case
    if not diag_dir.exists():
        return {
            "diagnostic_histogram_files": 0,
            "diagnostic_sample_row_files": 0,
            "diagnostic_manifest_files": 0,
        }
    return {
        "diagnostic_histogram_files": len(list(diag_dir.glob("*.hist.json"))),
        "diagnostic_sample_row_files": len(list(diag_dir.glob("*.sample-rows.jsonl"))),
        "diagnostic_manifest_files": len(list(diag_dir.glob("manifest.json"))),
    }


def parse_log(path: Path, exp_dir: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8", errors="replace")
    case = path.stem.replace(".raw", "")
    row: dict[str, Any] = {
        "case": case,
        "log": str(path.relative_to(exp_dir)),
        "ubatch": parse_ubatch(path),
    }
    for key, pattern in PATTERNS.items():
        match = pattern.search(text)
        if match:
            row[key] = float(match.group(1))
            if len(match.groups()) > 1:
                row[f"{key}_unc"] = float(match.group(2))
    chunk_matches = re.findall(r"^\s*(\d+)\s+", text, flags=re.MULTILINE)
    if chunk_matches:
        row["chunks_reported"] = int(chunk_matches[-1])
    row.update(count_diagnostic_files(exp_dir, case))
    return row


def parse_experiment(exp_dir: Path) -> list[dict[str, Any]]:
    logs_dir = exp_dir / "logs"
    rows = [parse_log(path, exp_dir) for path in sorted(logs_dir.glob("kld_*.raw.log"))]
    rows.sort(key=lambda row: (row.get("ubatch") is None, int(row.get("ubatch") or 0), str(row.get("case"))))
    return rows


def write_outputs(exp_dir: Path, rows: list[dict[str, Any]]) -> None:
    results_dir = exp_dir / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "metrics.json").write_text(json.dumps(rows, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    has_baseline_data = any((exp_dir / "baseline-logprobs").glob("*.kld"))
    title = "Baseline KLD Small Wikitext Results" if has_baseline_data else "KLD Baseline Data Comparison Results"

    fields = [
        "case",
        "ubatch",
        "chunks_reported",
        "mean_kld",
        "mean_kld_unc",
        "kld_p999",
        "mean_ppl_q",
        "mean_ppl_q_unc",
        "mean_ppl_base",
        "mean_ppl_base_unc",
        "mean_ppl_ratio",
        "mean_ppl_ratio_unc",
        "rms_dp_percent",
        "rms_dp_percent_unc",
        "same_top_p_percent",
        "same_top_p_percent_unc",
        "diagnostic_histogram_files",
        "diagnostic_sample_row_files",
        "diagnostic_manifest_files",
        "log",
    ]
    lines = ["\t".join(fields)]
    for row in rows:
        lines.append("\t".join("" if row.get(field) is None else str(row.get(field)) for field in fields))
    (results_dir / "metrics.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")

    md = [
        f"# {title}",
        "",
        "This summary is generated by `tools/kld/scripts/parse-kld-results.py`.",
        "",
    ]
    if not has_baseline_data:
        md.extend([
            "Baseline data source: `experiments/kld-baseline-data`.",
            "",
        ])
    if not rows:
        md.extend(
            [
                "No `logs/kld_*.raw.log` files were found yet. Generate baseline log-prob files with `RUN_BASELINE=1`, then run KLD cases with `RUN_KLD=1`.",
                "",
            ]
        )
    md.extend([
        "| case | ubatch | chunks | Mean KLD | 99.9% KLD | PPL(Q) | PPL(base) | PPL ratio | RMS dp | Same top p | diag hist | diag rows |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ])
    for row in rows:
        md.append(
            "| {case} | {ubatch} | {chunks} | {kld} +/- {kld_unc} | {kld_p999} | {ppl_q} +/- {ppl_q_unc} | "
            "{ppl_base} +/- {ppl_base_unc} | {ratio} +/- {ratio_unc} | {rms}% +/- {rms_unc}% | "
            "{top}% +/- {top_unc}% | {hist} | {sample_rows} |".format(
                case=row.get("case", ""),
                ubatch=row.get("ubatch", ""),
                chunks=row.get("chunks_reported", ""),
                kld=row.get("mean_kld", ""),
                kld_unc=row.get("mean_kld_unc", ""),
                kld_p999=row.get("kld_p999", ""),
                ppl_q=row.get("mean_ppl_q", ""),
                ppl_q_unc=row.get("mean_ppl_q_unc", ""),
                ppl_base=row.get("mean_ppl_base", ""),
                ppl_base_unc=row.get("mean_ppl_base_unc", ""),
                ratio=row.get("mean_ppl_ratio", ""),
                ratio_unc=row.get("mean_ppl_ratio_unc", ""),
                rms=row.get("rms_dp_percent", ""),
                rms_unc=row.get("rms_dp_percent_unc", ""),
                top=row.get("same_top_p_percent", ""),
                top_unc=row.get("same_top_p_percent_unc", ""),
                hist=row.get("diagnostic_histogram_files", 0),
                sample_rows=row.get("diagnostic_sample_row_files", 0),
            )
        )
    md.extend(["", "Artifacts:", "", "- Raw logs: `logs/`"])
    if has_baseline_data:
        md.append("- Baseline log-prob files: `baseline-logprobs/`")
    else:
        md.append("- Baseline log-prob files: `experiments/kld-baseline-data/baseline-logprobs/`")
    md.extend([
        "- Diagnostic summaries and samples: `diagnostics/`",
        "- Parsed metrics: `results/metrics.tsv`, `results/metrics.json`",
    ])
    (exp_dir / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Parse KLD logs and diagnostic artifact counts.")
    parser.add_argument("--exp-dir", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    rows = parse_experiment(args.exp_dir)
    write_outputs(args.exp_dir, rows)
    print(args.exp_dir / "results" / "metrics.tsv")


if __name__ == "__main__":
    main()
